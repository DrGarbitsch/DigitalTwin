"""List all nodes whose static/dynamic classification the heuristic rules change, in meaningful groups.

Input: a directory with the nodeset2owl exports of the default nodesets (built with --serverUri, see
build_exports.py) and their classification reports <export>.heuristic.tsv (--classification-report). Output:
Markdown, grouped by nodeset, rule, area (the part of the AddressSpace or the kind of definition) and changed subtree.

    python3 classification_changes.py <exports directory> <output.md>
"""

import csv
import glob
import os
import re
import sys
from collections import defaultdict

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import analyze  # noqa: E402

RULES = {
    'R1': 'R1 instance-with-Variables override (static → dynamic)',
    'R4': 'R4 definition fallback (instead of R5: dynamic → static)',
}
# core TypeDefinitions of the definition types and of folders -> area of the nodes R4 makes static
TYPE_AREAS = {'i=76': 'DataType encodings', 'i=72': 'type dictionaries and their descriptions',
              'i=69': 'type dictionaries and their descriptions', 'i=17589': 'dictionary entries',
              'i=17598': 'dictionary entries', 'i=17600': 'dictionary entries', 'i=61': 'entry folders'}
NUM = re.compile(r'^(i)=(\d+)$')


def order(nodeid):
    m = NUM.match(nodeid.rsplit(';', 1)[-1])
    return (0, int(m.group(2)), '') if m else (1, 0, nodeid)


def load_reports(directory):
    reports = {}
    for path in sorted(glob.glob(os.path.join(directory, '*.heuristic.tsv'))):
        with open(path) as f:
            reports[os.path.basename(path)[:-len('.owl.ttl.heuristic.tsv')]] = list(csv.DictReader(f, delimiter='\t'))
    return reports


class Paths:
    """Browse paths and HasChild parents of the nodes of all exports."""

    def __init__(self, directory):
        g, _ = analyze.load(directory)
        self.m = analyze.Model(g)
        self.by_nodeid = {}
        for n in self.m.nodes:
            nodeid = str(g.value(n, analyze.U.nodeId))
            if nodeid.startswith('svu='):  # the report identifies nodes without server
                nodeid = nodeid.split(';', 1)[1]
            if not nodeid.startswith('nsu='):
                nodeid = f'nsu=http://opcfoundation.org/UA/;{nodeid}'
            self.by_nodeid[nodeid] = n
        self.id_of = {n: nodeid for nodeid, n in self.by_nodeid.items()}

    def node(self, nodeid):
        return self.by_nodeid.get(nodeid)

    def path(self, nodeid):
        n = self.node(nodeid)
        if n is None:
            return None
        names = [self.m.name(n)] + [self.m.name(a) for a in self.m.ancestors(n)]
        return '/'.join(reversed(names))

    def parent_id(self, nodeid):
        n = self.node(nodeid)
        p = self.m.parent(n) if n is not None else None
        return self.id_of.get(p) if p is not None else None


def area_of(path, rule, row):
    if rule == 'R4':
        if row['TypeDefinition'] in TYPE_AREAS:
            return TYPE_AREAS[row['TypeDefinition']]
        if row['Reason'].startswith('R4: Variable of a type dictionary'):
            return 'type dictionaries and their descriptions'
        if row['Reason'].startswith('R4: definition node'):
            return 'other definitions'
        return 'Objects without Variables'
    if path is None or not path.startswith('Root/'):
        return 'not reachable from Root (prototypes)'
    parts = path.split('/')
    if len(parts) >= 4 and parts[2] == 'Server':
        return 'Objects/Server/' + parts[3]
    if len(parts) >= 3:
        return '/'.join(parts[1:3])
    return path


def main(directory, output):
    reports = load_reports(directory)
    paths = Paths(directory)
    out = ['# Static/dynamic classification: all changed nodes\n',
           'Generated by `classification_changes.py` from the nodeset2owl exports of the nodesets of '
           '`translate_default_nodesets.make` (UA-Nodeset UA-1.05.03-2023-12-15) and their '
           '`--classification-report`. Listed are all nodes whose classification differs from the standard rules '
           '(R3 NamespaceMetadata rule, R5 default fallback; `--strict-classification`). R1 overrules R3, R4 applies '
           'instead of R5 where R3 does not decide. The rules are described in the '
           '[README](../../README.md#static-and-dynamic-nodes) and in '
           '[heuristic-outliers.md](heuristic-outliers.md).\n',
           'Grouping: nodeset → rule → area (the part of the AddressSpace, e.g. `Objects/Server/ServerConfiguration`, '
           'or the kind of definition) → changed subtree (its topmost changed node, then all changed nodes '
           'below it).\n']
    summary = []
    sections = []
    for nodeset, rows in reports.items():
        counts = defaultdict(int)
        for r in rows:
            counts[r['Reason'][:2]] += 1
        summary.append((nodeset, counts['R1'], counts['R4']))
        if not rows:
            continue
        sections.append(f'## {nodeset}\n')
        changed = {r['NodeId']: r for r in rows}
        for rule in ('R1', 'R4'):
            rule_rows = [r for r in rows if r['Reason'].startswith(rule)]
            if not rule_rows:
                continue
            sections.append(f'### {RULES[rule]}: {len(rule_rows)} node(s)\n')
            # changed subtrees: topmost changed node (of the same rule) of each node
            roots = {}
            for r in rule_rows:
                nodeid, seen = r['NodeId'], set()
                parent = paths.parent_id(nodeid)
                while parent in changed and changed[parent]['Reason'][:2] == rule and parent not in seen:
                    seen.add(parent)
                    nodeid = parent
                    parent = paths.parent_id(nodeid)
                roots.setdefault(nodeid, []).append(r)
            areas = defaultdict(list)
            for root, members in roots.items():
                root_row = changed.get(root, members[0])
                areas[area_of(paths.path(root), rule, root_row)].append((root, members))
            for area in sorted(areas):
                subtrees = sorted(areas[area], key=lambda item: order(item[0]))
                total = sum(len(members) for _, members in subtrees)
                sections.append(f'#### {area} ({total})\n')
                sections.append('| NodeId | BrowseName | NodeClass | TypeDefinition | Browse path | Reason |')
                sections.append('|---|---|---|---|---|---|')
                for root, members in subtrees:
                    for r in sorted(members, key=lambda r: (r['NodeId'] != root, order(r['NodeId']))):
                        path = paths.path(r['NodeId']) or '—'
                        indent = '' if r['NodeId'] == root else '↳ '
                        reason = re.sub(r' \(nsu=[^)]*\)', '', r['Reason'][4:])
                        sections.append(f"| {indent}`{r['NodeId'].rsplit(';', 1)[-1]}` | {r['BrowseName']} | "
                                        f"{r['NodeClass']} | `{r['TypeDefinition']}` | {path} | {reason} |")
                sections.append('')
    out.append('## Summary\n')
    out.append('| Nodeset | R1 static → dynamic | R4 dynamic → static |')
    out.append('|---|---|---|')
    for nodeset, r1, r4 in summary:
        out.append(f'| {nodeset} | {r1} | {r4} |')
    out.append(f'| **Total** | **{sum(s[1] for s in summary)}** | **{sum(s[2] for s in summary)}** |\n')
    out += sections
    with open(output, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print(f'{output}: {sum(s[1] + s[2] for s in summary)} nodes')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
