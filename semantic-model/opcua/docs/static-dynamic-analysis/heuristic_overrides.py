"""Summarize the classification reports (nodeset2owl.py --classification-report) of the default nodesets into a
Markdown overview of the nodes which the heuristics classify differently than the standard rules.

    make -f translate_default_nodesets.make nodeset2owl 'DSB=--classification-report $@.heuristic.tsv'
    python3 docs/static-dynamic-analysis/heuristic_overrides.py <dir with *.heuristic.tsv> <output.md>
"""

import csv
import glob
import os
import re
import sys

PARENT = re.compile(r'Variable of instance (?:(?P<name>.*) \()?(?P<id>nsu=[^)]*)\)?$')


def load(path):
    with open(path) as f:
        return list(csv.DictReader(f, delimiter='\t'))


def numeric_order(nodeid):
    identifier = nodeid.rsplit(';', 1)[-1]
    return (0, int(identifier[2:])) if identifier.startswith('i=') else (1, identifier)


def to_dynamic(row):
    if 'Classification' in row:
        return row['Classification'] == 'dynamic'
    return row['Reason'] == 'instance with Variables' or row['Reason'].startswith('Variable of instance')


def main(directory, output):
    out = ['# Nodes classified differently by the heuristics\n',
           'Generated by `heuristic_overrides.py` from the `--classification-report` of nodeset2owl.py for the '
           'nodesets of `translate_default_nodesets.make` (UA-Nodeset UA-1.05.03-2023-12-15). Listed are the nodes '
           'whose classification differs from the standard rules (NamespaceMetadata, otherwise types and instance '
           'declarations static, instances dynamic; `--strict-classification`):\n',
           '- **static → dynamic**: an instance with Variables is dynamic together with its Variables, also against '
           'the NamespaceMetadata. An instance is listed with its Variables if it or one of its Variables is '
           'affected.',
           '- **dynamic → static**: where the NamespaceMetadata does not decide, an Object without Variables in its '
           'HasChild subtree and without dynamic HasChild parent is static (a Method follows its parent, its '
           'arguments the Method), and so are the Variables of the type dictionaries.\n']
    reports = sorted(glob.glob(os.path.join(directory, '*.heuristic.tsv')))
    summary = []
    sections = []
    for path in reports:
        all_rows = load(path)
        rows = [r for r in all_rows if to_dynamic(r)]
        static_rows = [r for r in all_rows if not to_dynamic(r)]
        nodeset = os.path.basename(path)[:-len('.owl.ttl.heuristic.tsv')]
        by_id = {r['NodeId']: r for r in rows}
        variables = {}  # instance id -> its Variables made dynamic
        names = {}
        for r in rows:
            m = PARENT.match(r['Reason'])
            if m:
                variables.setdefault(m.group('id'), []).append(r)
                names.setdefault(m.group('id'), m.group('name') or '')
        instances = sorted({r['NodeId'] for r in rows if r['Reason'] == 'instance with Variables'} | set(variables),
                           key=numeric_order)
        foreign = [i for i in instances if not i.startswith(rows[0]['NodeId'].rsplit(';', 1)[0])] if rows else []
        summary.append((nodeset, len(rows), len(instances) - len(foreign), len(foreign), len(static_rows)))
        if not all_rows:
            continue
        sections.append(f'## {nodeset}\n')
        if static_rows:
            sections.append(f'**dynamic → static**: {len(static_rows)} node(s).\n')
            sections.append('| NodeId | BrowseName | NodeClass | TypeDefinition | Reason |')
            sections.append('|---|---|---|---|---|')
            for r in sorted(static_rows, key=lambda r: numeric_order(r['NodeId'])):
                sections.append(f"| `{r['NodeId']}` | {r['BrowseName']} | {r['NodeClass']} | "
                                f"`{r['TypeDefinition']}` | {r['Reason']} |")
            sections.append('')
        if not rows:
            continue
        other = f', {len(foreign)} of them of another nodeset' if foreign else ''
        sections.append(f'**static → dynamic**: {len(rows)} node(s) of {len(instances)} instance(s){other}.\n')
        sections.append('| Instance | NodeId | TypeDefinition | instance itself | Variables made dynamic |')
        sections.append('|---|---|---|---|---|')
        for instance in instances:
            row = by_id.get(instance)
            own = sorted(variables.get(instance, []), key=lambda v: numeric_order(v['NodeId']))
            if row is not None:
                name, typedef, itself = row['BrowseName'], f"`{row['TypeDefinition']}`", 'made dynamic'
            else:
                name = names.get(instance) or '(another nodeset)'
                typedef, itself = '', 'dynamic anyway' if instance not in foreign else 'other nodeset'
            listed = ', '.join(f"{v['BrowseName']} (`{v['NodeId'].rsplit(';', 1)[-1]}`)" for v in own)
            listed = f': {listed}' if own else ''
            sections.append(f'| {name} | `{instance}` | {typedef} | {itself} | {len(own)}{listed} |')
        sections.append('')
    out.append('## Summary\n')
    out.append('| Nodeset | static → dynamic | Instances (own nodeset) | Instances of another nodeset '
               '| dynamic → static |')
    out.append('|---|---|---|---|---|')
    for nodeset, count, instances, foreign, to_static in summary:
        out.append(f'| {nodeset} | {count} | {instances} | {foreign} | {to_static} |')
    total = sum(s[1] for s in summary)
    out.append(f'| **Total** | **{total}** | **{sum(s[2] for s in summary)}** | **{sum(s[3] for s in summary)}** '
               f'| **{sum(s[4] for s in summary)}** |\n')
    out += sections
    open(output, 'w').write('\n'.join(out) + '\n')
    print(f'{output}: {len(reports)} reports, {total} nodes')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
