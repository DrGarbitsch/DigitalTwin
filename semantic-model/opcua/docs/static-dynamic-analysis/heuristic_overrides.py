"""Summarize the classification reports (nodeset2owl.py --classification-report) of the default nodesets into a
Markdown overview of the instances which the instance-with-variables heuristic makes dynamic.

    make -f translate_default_nodesets.make nodeset2owl 'DSB=--classification-report $@.heuristic.tsv'
    python3 docs/static-dynamic-analysis/heuristic_overrides.py <dir with *.heuristic.tsv> <output.md>
"""

import csv
import glob
import os
import re
import sys

PARENT = re.compile(r'Variable of instance (?:(?P<name>.*) \()?(?P<id>nsu=[^)]*)\)?$')


def load(path):
    with open(path) as f:
        return list(csv.DictReader(f, delimiter='\t'))


def numeric_order(nodeid):
    identifier = nodeid.rsplit(';', 1)[-1]
    return (0, int(identifier[2:])) if identifier.startswith('i=') else (1, identifier)


def main(directory, output):
    out = ['# Nodes made dynamic by the instance-with-variables heuristic\n',
           'Generated by `heuristic_overrides.py` from the `--classification-report` of nodeset2owl.py for the '
           'nodesets of `translate_default_nodesets.make` (UA-Nodeset UA-1.05.03-2023-12-15). Listed are the nodes '
           'which NamespaceMetadata or the default rule classify **static**, but the heuristic classifies '
           '**dynamic**: an instance with Variables is dynamic together with its Variables '
           '(`--strict-classification` disables it). Nodes which are dynamic anyway are not listed; an instance '
           'is listed with its Variables if it or one of its Variables is affected.\n']
    reports = sorted(glob.glob(os.path.join(directory, '*.heuristic.tsv')))
    summary = []
    sections = []
    for path in reports:
        rows = load(path)
        nodeset = os.path.basename(path)[:-len('.owl.ttl.heuristic.tsv')]
        by_id = {r['NodeId']: r for r in rows}
        variables = {}  # instance id -> its Variables made dynamic
        names = {}
        for r in rows:
            m = PARENT.match(r['Reason'])
            if m:
                variables.setdefault(m.group('id'), []).append(r)
                names.setdefault(m.group('id'), m.group('name') or '')
        instances = sorted({r['NodeId'] for r in rows if r['Reason'] == 'instance with Variables'} | set(variables),
                           key=numeric_order)
        foreign = [i for i in instances if not i.startswith(rows[0]['NodeId'].rsplit(';', 1)[0])] if rows else []
        summary.append((nodeset, len(rows), len(instances) - len(foreign), len(foreign)))
        if not rows:
            continue
        sections.append(f'## {nodeset}\n')
        other = f', {len(foreign)} of them of another nodeset' if foreign else ''
        sections.append(f'{len(rows)} node(s) of {len(instances)} instance(s){other}.\n')
        sections.append('| Instance | NodeId | TypeDefinition | instance itself | Variables made dynamic |')
        sections.append('|---|---|---|---|---|')
        for instance in instances:
            row = by_id.get(instance)
            own = sorted(variables.get(instance, []), key=lambda v: numeric_order(v['NodeId']))
            if row is not None:
                name, typedef, itself = row['BrowseName'], f"`{row['TypeDefinition']}`", 'made dynamic'
            else:
                name = names.get(instance) or '(another nodeset)'
                typedef, itself = '', 'dynamic anyway' if instance not in foreign else 'other nodeset'
            listed = ', '.join(f"{v['BrowseName']} (`{v['NodeId'].rsplit(';', 1)[-1]}`)" for v in own)
            listed = f': {listed}' if own else ''
            sections.append(f'| {name} | `{instance}` | {typedef} | {itself} | {len(own)}{listed} |')
        sections.append('')
    out.append('## Summary\n')
    out.append('| Nodeset | Nodes made dynamic | Instances (own nodeset) | Instances of another nodeset |')
    out.append('|---|---|---|---|')
    for nodeset, count, instances, foreign in summary:
        out.append(f'| {nodeset} | {count} | {instances} | {foreign} |')
    total = sum(s[1] for s in summary)
    out.append(f'| **Total** | **{total}** | **{sum(s[2] for s in summary)}** | **{sum(s[3] for s in summary)}** |\n')
    out += sections
    open(output, 'w').write('\n'.join(out) + '\n')
    print(f'{output}: {len(reports)} reports, {total} nodes')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
